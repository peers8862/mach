#!/usr/bin/env bash
# lib/common.sh: shared helpers for mach's bash scripts. Source it; don't run it.
# bash 3.2 compatible (macOS 12): no associative arrays, mapfile, ${var,,}, |&, coproc, declare -n.

# --- exit codes -------------------------------------------------------------
# shellcheck disable=SC2034  # part of the shared API: not every script uses every code
MACH_EXIT_OK=0
MACH_EXIT_WARN=1
MACH_EXIT_FAIL=2
MACH_EXIT_WAIT=3

# --- locations --------------------------------------------------------------
mach_home_dir() {
  # directory of the mach checkout (set by bin/mach; derive it if sourced directly)
  if [ -n "${MACH_HOME:-}" ]; then printf '%s' "$MACH_HOME"; return; fi
  local d
  d=$(cd -P "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
  printf '%s' "$d"
}

mach_host() {
  # MACH_HOST overrides; else the python helper (short hostname mapped by [machines.match] in the config); else the short hostname
  if [ -n "${MACH_HOST:-}" ]; then printf '%s' "$MACH_HOST"; return; fi
  local py out
  py=$(mach_python 2>/dev/null) && out=$("$py" "$(mach_home_dir)/lib/mach_common.py" host 2>/dev/null) && [ -n "$out" ] && { printf '%s' "$out"; return; }
  hostname -s 2>/dev/null || hostname 2>/dev/null || echo unknown
}

# mach_cfg <dotted.key>: one config value (lists print one item per line); empty when unset or when python is missing
mach_cfg() {
  local py
  py=$(mach_python 2>/dev/null) || return 0
  "$py" "$(mach_home_dir)/lib/mach_common.py" get "$1" 2>/dev/null
}

mach_os() {
  # MACH_OS overrides (tests): darwin | linux
  if [ -n "${MACH_OS:-}" ]; then printf '%s' "$MACH_OS"; return; fi
  case "$(uname -s)" in
    Darwin) printf 'darwin' ;;
    *) printf 'linux' ;;
  esac
}

mach_is_mac() { [ "$(mach_os)" = "darwin" ]; }

MACH_MF_ROOT=${MACH_MF_ROOT:-$HOME/machine-flows}
MACH_STAGING=${MACH_STAGING:-$HOME/machine-flows-staging}
MACH_STATE_DIR=${MACH_STATE_DIR:-$MACH_STAGING/docs-index}
export MACH_MF_ROOT MACH_STAGING MACH_STATE_DIR

mach_tilde() {
  case "$1" in
    "$HOME") printf '~' ;;
    "$HOME"/*) printf '~%s' "${1#"$HOME"}" ;;
    *) printf '%s' "$1" ;;
  esac
}

# --- output -----------------------------------------------------------------
if [ -t 1 ] && [ -z "${NO_COLOR:-}" ] && [ -z "${MACH_NO_COLOR:-}" ]; then
  C_OK=$'\033[32m'; C_WARN=$'\033[33m'; C_FAIL=$'\033[31m'; C_INFO=$'\033[36m'; C_OFF=$'\033[0m'
else
  C_OK=''; C_WARN=''; C_FAIL=''; C_INFO=''; C_OFF=''
fi

ok()   { printf '%sOK%s    %s\n' "$C_OK" "$C_OFF" "$*"; }
warn() { printf '%sWARN%s  %s\n' "$C_WARN" "$C_OFF" "$*"; }
fail() { printf '%sFAIL%s  %s\n' "$C_FAIL" "$C_OFF" "$*"; }
info() { printf '%sINFO%s  %s\n' "$C_INFO" "$C_OFF" "$*"; }
err()  { printf 'mach: %s\n' "$*" >&2; }
die()  { err "$*"; exit "$MACH_EXIT_FAIL"; }

# --- flags shared by commands ----------------------------------------------
mach_flag_on() { case "${1:-}" in ''|0|false|no) return 1 ;; *) return 0 ;; esac; }

# --- temp dirs (under staging, never /tmp unless staging is unusable) ------
mach_mktemp_dir() {
  local base="$MACH_STAGING/tmp" d
  if mkdir -p "$base" 2>/dev/null; then
    d=$(mktemp -d "$base/mach.XXXXXX") && { printf '%s' "$d"; return 0; }
  fi
  mktemp -d "${TMPDIR:-/tmp}/mach.XXXXXX"
}

# --- backup + rollback ------------------------------------------------------
# usage: mach_bk_init <cmd>; mach_bk_copy <path>; mach_bk_created <path>; mach_bk_link <symlink>; mach_bk_finish
MACH_BK_DIR=""
MACH_BK_N=0
MACH_BK_LINES=""

mach_bk_init() {
  MACH_BK_DIR="$MACH_STAGING/backups/$(date +%Y%m%d-%H%M%S)-mach-$1"
  MACH_BK_N=0
  MACH_BK_LINES=""
  mkdir -p "$MACH_BK_DIR" || die "cannot create backup dir $MACH_BK_DIR"
}

mach_bk_copy() {
  # back up an existing regular file before it is changed
  local src="$1" dest
  [ -e "$src" ] || { mach_bk_created "$src"; return 0; }
  MACH_BK_N=$((MACH_BK_N + 1))
  dest="$MACH_BK_DIR/$(printf '%03d' "$MACH_BK_N")-$(basename "$src")"
  cp -p "$src" "$dest" || die "backup failed for $src"
  MACH_BK_LINES="cp -p $(printf '%q' "$dest") $(printf '%q' "$src")
$MACH_BK_LINES"
}

mach_bk_created() {
  MACH_BK_LINES="rm -rf $(printf '%q' "$1")
$MACH_BK_LINES"
}

mach_bk_link() {
  # record a symlink (and its target) that is about to be removed
  local l="$1" tgt
  tgt=$(readlink "$l")
  printf '%s\t%s\t%s\t%s\n' "$(date '+%F %T %Z')" "$(mach_host)" "$l" "$tgt" >> "$MACH_BK_DIR/removed-links.tsv"
  MACH_BK_LINES="rm -f $(printf '%q' "$l") && ln -s $(printf '%q' "$tgt") $(printf '%q' "$l")
$MACH_BK_LINES"
}

mach_bk_finish() {
  local script="$MACH_BK_DIR/rollback.sh"
  {
    printf '#!/usr/bin/env bash\n# generated by mach: restores what this run changed\nset -u\n'
    printf '%s\n' "$MACH_BK_LINES"
  } > "$script"
  chmod +x "$script"
  printf 'backup: %s\n' "$(mach_tilde "$MACH_BK_DIR")"
  printf 'rollback: bash %s\n' "$(mach_shell_path "$script")"
}

# mach_shell_path <path>: a path to paste into a shell. '~/…' stays unquoted (so it expands); the rest is %q-quoted.
mach_shell_path() {
  local t
  t=$(mach_tilde "$1")
  # shellcheck disable=SC2088  # a literal '~/' is intended: it is pasted into the user's shell, which expands it
  if [ "${t:0:2}" = '~/' ]; then
    printf '~/%q' "${t:2}"
  else
    printf '%q' "$t"
  fi
}

# --- python helper ----------------------------------------------------------
mach_python() {
  # prefer a python3 >= 3.9; the Mac's /usr/bin/python3 is 3.9
  local c
  for c in python3 /usr/bin/python3 python3.12 python3.11 python3.10 python3.9; do
    if command -v "$c" >/dev/null 2>&1 && "$c" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 9) else 1)' 2>/dev/null; then
      printf '%s' "$c"; return 0
    fi
  done
  return 1
}
