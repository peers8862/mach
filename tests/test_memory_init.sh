#!/usr/bin/env bash
# shellcheck disable=SC2034,SC1091,SC2012,SC2015,SC2016,SC2086,SC2088,SC2221,SC2222  # test scripts: intentional shortcuts
# memory init (plan 09 skeleton), review messages when the skeleton is missing, regenerated INDEX.md, --save in a minimal environment.
TEST_NAME=memory_init
. "$(dirname "$0")/lib.sh"
new_sandbox
MF="$MACH_MF_ROOT"
LS="$MF/service-memories/lessons"

# --- review before init: INFO, rc 0, says how to fix; no "()" in the count line
run memory review
assert_rc 0 "review without a lessons folder"
assert_contains "run: mach memory init --apply" "review: tells how to fix a missing folder"
assert_contains "INFO" "review: missing folder is INFO"
assert_not_contains "WARN" "review: missing folder is not a warning"
assert_not_contains "()" "review: no empty parentheses"

# --- init previews first
run memory init
assert_rc 0 "init preview"
assert_contains "create file" "init preview lists creations"
assert_contains "preview only" "init: preview says so"
assert_no_file "$LS/README.md" "init preview wrote nothing"
run --dry-run memory init --apply
assert_no_file "$LS/INDEX.md" "init: global --dry-run wins over --apply"

# --- existing reviews/ folder and a hand-written README must survive
mkdir -p "$LS/reviews"; printf 'keep me\n' > "$LS/reviews/README.md"; printf 'my own readme\n' > "$LS/README.md"
run memory init --apply
assert_rc 0 "init --apply"
assert_contains "rollback: bash ~/" "init: rollback line"
assert_file_has "$LS/README.md" "my own readme" "init: existing README.md not overwritten"
assert_file_has "$LS/reviews/README.md" "keep me" "init: reviews/ untouched"
for t in sync ai-tools cli mcp drafts macos linux git coding projects archived; do
  if [ -d "$LS/$t" ]; then pass; else flunk "init: topic folder $t missing"; fi
done
assert_file "$LS/INDEX.md" "init: INDEX.md"
assert_file_has "$LS/INDEX.md" "generated by mach memory" "init: INDEX.md has the generated marker"
assert_file_has "$LS/INDEX.md" "Live lessons: 0" "init: INDEX.md header counts"
assert_file_has "$LS/INDEX.md" "AGENTS.md: absent" "init: INDEX.md header AGENTS.md size"
assert_file "$LS/archived/INDEX.md" "init: archived/INDEX.md"
run memory review
assert_rc 0 "review after init is clean"
assert_contains "lessons: 0" "review: count line"
assert_contains "OK  no findings" "review: no findings after init"
run memory init --apply
assert_contains "nothing to do" "init is idempotent"

# --- rollback removes only what init created
BK=$(ls -d "$MACH_STAGING"/backups/*-mach-memory | head -n 1)
printf 'later\n' > "$LS/cli/2026-10-08-added-later.md"
bash "$BK/rollback.sh" >/dev/null 2>&1
assert_file "$LS/cli/2026-10-08-added-later.md" "rollback: keeps files added later (and so their folder)"
assert_file_has "$LS/README.md" "my own readme" "rollback: keeps the pre-existing README.md"
assert_file_has "$LS/reviews/README.md" "keep me" "rollback: keeps reviews/"
assert_no_file "$LS/INDEX.md" "rollback: removes the INDEX.md init created"
assert_no_file "$LS/sync" "rollback: removes the empty topic folders init created"
rm -f "$LS/cli/2026-10-08-added-later.md"

# --- INDEX.md is generated from frontmatter; --reindex and review --apply regenerate it
run memory init --apply
mk() { # mk <topic> <file> <title> <status> <conf>
  cat > "$LS/$1/$2" <<EOT
---
id: L-$2
title: $3
date: 2026-10-01
source: test
scope:
  tools: [cursor-agent, grokcli-agent]
  machines: [all]
confidence: $5
review_by: 2027-01-01
status: $4
---
body
EOT
}
mk cli 2026-10-01-bare-agent.md "Installers recreate a bare agent command" active high
mk sync 2026-10-02-wip.md "Brand new idea about tmux" proposed low
mk sync 2026-10-03-old.md "Something replaced long ago" superseded low
run memory init --reindex --apply
assert_contains "regenerated 1" "init --reindex regenerates INDEX.md"
assert_file_has "$LS/INDEX.md" "[cli] Installers recreate a bare agent command · cursor-agent, grokcli-agent · all · high · review 2027-01-01 → cli/2026-10-01-bare-agent.md" "index: line format"
assert_file_has "$LS/INDEX.md" "[sync] [proposed] Brand new idea about tmux" "index: proposed tag"
assert_file_lacks "$LS/INDEX.md" "replaced long ago" "index: superseded lessons are not listed"
assert_file_has "$LS/INDEX.md" "Live lessons: 2 (sync 1 · cli 1)" "index: counts per topic"
run memory review --apply
assert_file "$LS/archived/sync/2026-10-03-old.md" "review --apply archives the superseded lesson"
assert_file_has "$LS/INDEX.md" "generated by mach memory" "review --apply keeps the generated marker"
assert_file_has "$LS/archived/INDEX.md" "Something replaced long ago" "review --apply: archived index"

# --- hand-edited INDEX.md (no marker) is not replaced by review --apply
printf '# my index\n- [cli] mine → cli/2026-10-01-bare-agent.md\n- [sync] gone → sync/2026-10-04-gone.md\n' > "$LS/INDEX.md"
mk sync 2026-10-04-gone.md "Gone soon" superseded low
run memory review --apply
assert_file_has "$LS/INDEX.md" "my index" "hand-edited INDEX.md kept"
assert_file_lacks "$LS/INDEX.md" "2026-10-04-gone" "hand-edited INDEX.md: archived line removed"

# --- --save with no tty and a minimal environment (like a systemd user service)
rm -rf "$SANDBOX/svc"; mkdir -p "$SANDBOX/svc/home/machine-flows-staging" "$SANDBOX/svc/home/machine-flows/service-memories/lessons/cli"
SVC="$SANDBOX/svc/home"
OUT=$(env -i HOME="$SVC" PATH=/usr/bin:/bin "$MACH" memory review --save </dev/null 2>&1); RC=$?
assert_rc 0 "minimal env: review --save"
assert_contains "saved report:" "minimal env: says where it saved"
MONTH=$(date +%Y-%m)
assert_file "$SVC/machine-flows/service-memories/lessons/reviews/$MONTH.md" "minimal env: YYYY-MM.md written"
assert_file_has "$SVC/machine-flows/service-memories/lessons/reviews/$MONTH.md" "mach memory review" "minimal env: report content"
assert_file "$SVC/machine-flows/service-memories/lessons/reviews/README.md" "minimal env: reviews README"
OUT=$(env -i HOME="$SVC" PATH=/usr/bin:/bin "$MACH" memory init --apply </dev/null 2>&1); RC=$?
assert_rc 0 "minimal env: init --apply"
assert_file "$SVC/machine-flows/service-memories/lessons/INDEX.md" "minimal env: init wrote INDEX.md"

finish
